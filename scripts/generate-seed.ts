/**
 * Generates supabase/seed.sql (demo data) from the app's sample data, using the
 * same record <-> row mapping the app uses at runtime.
 *
 *   npm run db:seed:generate
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COLLECTIONS, toRow } from '../src/lib/backend/schema';
import {
  PRODUCERS,
  SKUS,
  USERS,
  stockMovements,
  MOCK_SALES_ORDERS,
  MOCK_SHIPMENTS,
} from '../src/app/data/mockData';

const companies = [
  { id: 'comp-001', name: 'MarketSell Trading', country: 'El Salvador', city: 'San Salvador', contactEmail: 'sales@marketsell.com', status: 'Active', createdAt: '2024-01-01' },
  { id: 'comp-002', name: 'Coffee Imports Ltd', country: 'Colombia', city: 'Bogotá', contactEmail: 'info@coffeeimports.com', status: 'Active', createdAt: '2024-01-15' },
  { id: 'comp-003', name: 'Brazilian Coffee Co', country: 'Brazil', city: 'São Paulo', contactEmail: 'contact@brazilcoffee.com', status: 'Active', createdAt: '2024-02-01' },
];

const members = USERS.map((u) => ({
  userId: u.userId,
  email: `user${u.userId}@marketsell.com`,
  name: `User ${u.userId}`,
  sellerGroup: u.sellerGroup,
  buyerGroup: u.buyerGroup,
  agentGroup: u.agentGroup,
  buyerRating: u.buyerRating,
  sellerRating: u.sellerRating,
  agentRating: u.agentRating,
}));

const userRights = [
  { userId: 1, companyId: 'comp-001', canSell: true, canBeAgent: true, canPlaceOrders: true, canUpdateData: true, canAuthoriseUsers: true, role: 'buyer' },
  { userId: 1, companyId: 'comp-001', canSell: true, canBeAgent: true, canPlaceOrders: true, canUpdateData: true, canAuthoriseUsers: false, role: 'seller' },
  { userId: 2, companyId: 'comp-002', canSell: true, canBeAgent: false, canPlaceOrders: true, canUpdateData: true, canAuthoriseUsers: false, role: 'buyer' },
];

const data: Record<string, any[]> = {
  members,
  companies,
  user_rights: userRights,
  producers: PRODUCERS,
  skus: SKUS.map((s: any) => ({ companyId: 'comp-001', ...s })),
  stock_movements: stockMovements.map((m: any) => ({ companyId: 'comp-001', ...m })),
  sales_orders: MOCK_SALES_ORDERS.map((o: any) => ({ ...o, sellerCompanyId: 'comp-001' })),
  shipments: MOCK_SHIPMENTS.map((s: any) => ({ companyId: 'comp-001', ...s })),
};

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;

let sql = `-- Demo data for MarketSell. Generated by scripts/generate-seed.ts — do not edit by hand.
-- Applied automatically by \`supabase db reset\`; on a hosted project run it once in the SQL editor if you want sample data.

begin;
`;
for (const def of COLLECTIONS) {
  const records = data[def.table];
  if (!records?.length) continue;
  const rows = records.map((r) => toRow(def, r));
  const cols = Object.keys(rows[0]).join(', ');
  sql += `
insert into public.${def.table} (${cols})
select ${cols} from jsonb_populate_recordset(null::public.${def.table}, ${quote(JSON.stringify(rows))}::jsonb)
on conflict (${def.pkColumn}) do nothing;
`;
}
sql += `
-- Ids above 1000 are handed out to new sign-ups.
select setval('public.members_id_seq', greatest(1000, (select coalesce(max(user_id), 0) + 1 from public.members)), false);

commit;
`;

const out = resolve(import.meta.dirname, '../supabase/seed.sql');
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
